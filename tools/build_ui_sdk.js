#!/usr/bin/env node
/**
 * [INPUT]: 固定 SDK、esbuild、ui_sdk_entry.mjs 与 lock。
 * [OUTPUT]: --write 生成离线 UI SDK 包、许可证和摘要；默认复核确定性输出。
 * [POS]: 仅编译实际使用的组件，不把 npm 或构建器带入 App。
 * [PROTOCOL]: 变更时更新此头部，然后检查 CLAUDE.md
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const esbuild = require('esbuild');
const repo = path.resolve(__dirname, '..');
const writing = process.argv.includes('--write');
const sha = (data) => crypto.createHash('sha256').update(data).digest('hex');
const pkg = (name) => JSON.parse(fs.readFileSync(path.resolve(path.dirname(require.resolve(name)), '../package.json')));
const sdkVersion = pkg('@ui-sdk/web').version;
assert.equal(pkg('@ui-sdk/core').version, sdkVersion);
assert.equal(sdkVersion, '0.1.0-beta.5');
const result = esbuild.buildSync({
  absWorkingDir: repo, entryPoints: ['tools/ui_sdk_entry.mjs'], outfile: 'ui-sdk.js',
  bundle: true, format: 'iife', platform: 'browser', target: ['safari16.4', 'chrome120'],
  minify: true, treeShaking: true, legalComments: 'eof', charset: 'utf8',
  write: false, metafile: true,
  banner: { js: '/* Generated by tools/build_ui_sdk.js; UI SDK Apache-2.0, see ui-sdk.LICENSE. Do not edit. */' },
});
const data = Buffer.from(result.outputFiles[0].contents);
const sdkRoot = path.resolve(path.dirname(require.resolve('@ui-sdk/web')), '..');
const license = fs.readFileSync(path.join(sdkRoot, 'LICENSE'));
const inventory = JSON.parse(fs.readFileSync(path.join(repo, 'tools/ui_sdk_components.json'), 'utf8'));
const components = inventory.primitives.map(component => component.name);
const manifest = Buffer.from(JSON.stringify({ sdkVersion, esbuildVersion: esbuild.version, components, implementations: inventory,
  files: [{ path: 'ui-sdk.js', bytes: data.length, sha256: sha(data) },
    { path: 'ui-sdk.LICENSE', bytes: license.length, sha256: sha(license) }] }, null, 2) + '\n');
for (const [name, bytes] of [['ui-sdk.js', data], ['ui-sdk.LICENSE', license], ['ui-sdk.manifest.json', manifest]]) {
  const target = path.join(repo, 'renderer', name);
  if (writing) fs.writeFileSync(target, bytes);
  else assert.deepEqual(fs.readFileSync(target), bytes, `${name} is stale; run npm run build:ui-sdk`);
}
process.stdout.write(`UI SDK ${sdkVersion}: ${components.length} components, ${data.length} bundled bytes, ${writing ? 'written' : 'verified'}\n`);
