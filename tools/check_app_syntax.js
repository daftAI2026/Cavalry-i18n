function runAppSyntaxCheck(files = APP_SYNTAX_FILES, options = {}) {
  const cwd = options.cwd || REPO_ROOT;
  const run = options.spawnSync || spawnSync;
  for (const file of files) {
    const result = run(process.execPath, ['--check', file], {
      cwd,
      shell: false,
      stdio: 'inherit',
    });
    if (result.error) {
      process.stderr.write('check_app_syntax: ' + file + ': ' + result.error.message + '\n');
      return 1;
    }
    if (result.status !== 0) {
      if (result.status === null) {
        process.stderr.write('check_app_syntax: ' + file + ': Node exited by ' + (result.signal || 'unknown signal') + '\n');
      }
      return Number.isInteger(result.status) ? result.status : 1;
    }
  }
  return 0;
}

function main(argv) {
  if (argv.length !== 0) {
    process.stderr.write('usage: node tools/check_app_syntax.js\n');
    return 2;
  }
  return runAppSyntaxCheck();
}

if (require.main === module) process.exitCode = main(process.argv.slice(2));

module.exports = { APP_SYNTAX_FILES, runAppSyntaxCheck };
